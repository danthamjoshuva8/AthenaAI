from app.database.models import StockMaster
from app.models.sector import Sector
from app.models.trade_candidate import TradeCandidate
from app.services.market_service import MarketService
from app.services.strategy_service import StrategyService
from sqlalchemy.orm import Session

from app.market.market_analyzer import MarketAnalyzer
from app.market.symbol_provider import load_nifty200_symbols
from app.trade_selection.news_provider import NewsProvider
from app.trade_selection.position_sizer import PositionSizer
from app.trade_selection.sector_analyzer import SectorAnalyzer
from app.trade_selection.trade_ranking_engine import TradeRankingEngine
from app.market.market_engine import MarketEngine


class TradeSelectionEngine:
    """
    Coordinates the trade selection workflow for the NIFTY 200 universe.

    Generates trading signals, builds trade candidates, enriches them
    with historical news and market context, calculates sector strength,
    determines position sizes, and ranks the resulting candidates.
    """

    def __init__(self):
        """
        Initialize the services and engines required for trade selection.

        Creates the strategy, ranking, position sizing, market analysis,
        sector analysis, news retrieval, and market data components.
        """

        # Initialize the strategy service used to generate trading signals.
        self.strategy = StrategyService()

        # Initialize the engine responsible for ranking trade candidates.
        self.ranking = TradeRankingEngine()

        # Initialize the position sizing calculator.
        self.position_sizing = PositionSizer()

        # Initialize the market context analyzer.
        self.market_context = MarketAnalyzer()

        # Initialize the sector strength analyzer.
        self.sector_strength = SectorAnalyzer()

        # Initialize the historical news provider.
        self.news_service = NewsProvider()

        # Initialize the market data engine.
        self.market_engine = MarketEngine()

    def build_candidates(
        self,
        db: Session,
        symbol: str,
        signals: list[dict]
    ):
        """
        Build trade candidates from the generated trading signals.

        Processes BUY signals, validates entry and stop-loss prices,
        retrieves historical news, enriches candidates with market and
        sector information, calculates position sizes, and collects
        the resulting candidates.

        Args:
            db: SQLAlchemy database session used for market and stock data.
            symbol: Stock symbol being evaluated.
            signals: Trading signals generated by the strategy service.

        Returns:
            A list of trade candidates created from valid BUY signals.
        """

        # Store the trade candidates generated for this symbol.
        candidates = []

        # Process each signal generated by the trading strategy.
        for signal in signals:

            # Only BUY signals are eligible for trade candidate generation.
            if signal["signal"] != "BUY":
                continue

            # Retrieve the proposed entry and stop-loss prices.
            entry = signal.get("entry_price")

            stop = signal.get("stop_loss")

            # Skip signals with missing entry or stop-loss prices.
            if entry is None or stop is None:
                continue

            # Calculate the monetary risk per share.
            risk = entry - stop

            # Skip trades where the stop-loss is not below the entry price.
            if risk <= 0:
                continue

            # Retrieve historical news available on or before the signal date.
            news = self.news_service.get_historical_news(

                symbol,

                signal["date"]
            )

            # Create a trade candidate using the signal's calculated values.
            candidate = TradeCandidate(

                symbol=symbol,

                signal_date=signal["date"],

                entry_price=entry,

                stop_loss=stop,

                risk_per_share=risk,

                # Calculate the 2R and 3R profit targets.
                target_2r=entry + (2 * risk),

                target_3r=entry + (3 * risk),

                # Calculate relative volume using the 20-period average.
                volume_ratio=(
                    signal["volume"] / signal["volume20"]
                    if signal.get("volume20")
                    else 0
                ),

                # Copy the moving average distance and candle quality metrics.
                distance_from_ma=signal.get(
                    "distance_from_ma",
                    0
                ),

                body_percent=signal.get(
                    "body_percent",
                    0
                ),

                volume_confirmation=signal.get(
                    "volume_confirmation",
                    False
                ),

                quality_pass=signal.get(
                    "quality_pass",
                    False
                ),

                # Preserve the original signal data for further analysis.
                metadata=signal

            )

            # Attach historical news to the original signal metadata.
            signal["historical_news"] = news

            try:

                # Retrieve NIFTY historical data up to the candidate's signal date.
                nifty_df = self.market_engine.get_nifty_history(
                    db,
                    candidate.signal_date
                )

                # Prepare NIFTY data with the required market context indicators.
                nifty_df = self.market_engine.prepare_nifty_context(
                    nifty_df
                )

                # Continue market and sector analysis when prepared data is available.
                if not nifty_df.empty:

                    # Analyze the overall market conditions.
                    market_state = self.market_context.analyze(
                        nifty_df
                    )

                    # Assign the overall market score to the candidate.
                    candidate.market_score = market_state.total_score

                    # Store market context inside the original signal metadata.
                    signal["market_trend"] = market_state.trend
                    signal["market_score"] = market_state.total_score

                    # Store optional market indicator values when available.
                    signal["market_ma_distance"] = getattr(
                        market_state,
                        "ma_distance_percent",
                        None
                    )

                    signal["market_ma_slope"] = getattr(
                        market_state,
                        "ma_slope_percent",
                        None
                    )

                    signal["market_momentum"] = getattr(
                        market_state,
                        "momentum_percent",
                        None
                    )

                    signal["market_atr_percent"] = getattr(
                        market_state,
                        "atr_percent",
                        None
                    )

                    # Retrieve stock master information for the current symbol.
                    stock = (
                        db.query(StockMaster)
                        .filter(StockMaster.symbol == symbol)
                        .first()
                    )

                    # Attach industry and market capitalization information.
                    signal["industry"] = getattr(stock, "industry", None)
                    signal["market_cap"] = getattr(stock, "market_cap", None)

                    # Determine the candidate's sector from stock master data.
                    candidate.sector = (
                        Sector(stock.sector)
                        if stock and stock.sector
                        else Sector.UNKNOWN
                    )

                    # Store the sector identifier in the signal metadata.
                    signal["sector"] = (
                        candidate.sector.value
                        if candidate.sector
                        else "UNKNOWN"
                    )

                    # Calculate sector strength using historical sector data.
                    candidate.sector_score = (
                        self.sector_strength.get_sector_score(
                            db=db,
                            sector=candidate.sector,
                            signal_date=candidate.signal_date
                        )
                    )

                    # Store the calculated sector score in signal metadata.
                    signal["sector_score"] = candidate.sector_score

            except Exception as ex:

                # Report market or sector context processing failures.
                print(
                    f"Market Context Error ({symbol}): {ex}"
                )

            # Calculate the candidate's position size using the configured
            # portfolio value and risk percentage.
            candidate = self.position_sizing.calculate_position_size(

                candidate,

                portfolio_value=10000000,

                risk_percent=1

            )

            # Add the completed candidate to the results for this symbol.
            candidates.append(candidate)

        # Return all valid BUY candidates generated for the symbol.
        return candidates

    def scan_market(
        self,
        db: Session
    ):
        """
        Scan the NIFTY 200 universe and rank eligible trade candidates.

        Loads the stock universe, generates trading signals for each
        symbol, builds candidates from valid BUY signals, collects
        candidates across all symbols, and ranks them by trade quality.

        Args:
            db: SQLAlchemy database session used during market scanning.

        Returns:
            All generated trade candidates ranked by their total
            trade quality scores.
        """

        # Collect candidates generated across the entire stock universe.
        all_candidates = []

        # Load the current NIFTY 200 stock symbols.
        symbols = load_nifty200_symbols()

        # Process each symbol independently.
        for symbol in symbols:

            try:

                # Generate trading signals for the current stock.
                signals = self.strategy.generate_signals(
                    db,
                    symbol
                )

                # Convert eligible BUY signals into trade candidates.
                candidates = self.build_candidates(
                    db,
                    symbol,
                    signals
                )

                # Add the symbol's candidates to the overall collection.
                all_candidates.extend(
                    candidates
                )

            except Exception as ex:

                # Report scanning failures without stopping the remaining symbols.
                print(

                    f"Scan failed for {symbol}: {ex}"

                )

        # Rank all collected candidates by their trade quality scores.
        return self.ranking.rank_candidates(
            all_candidates
        )