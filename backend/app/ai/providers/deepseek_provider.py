
"""
DeepSeek LLM provider for AthenaAI.

Responsibilities:
    - Sending trade analysis prompts to the DeepSeek API.
    - Handling HTTP communication and API errors.
    - Parsing and validating JSON responses.
    - Tracking API execution time and token usage.
    - Returning structured analysis results to AIOrchestrator.

This provider implements the BaseLLMProvider interface.

Logging:
    - API request started.
    - API request completed.
    - API communication failures.
    - Response parsing failures.
    - Execution duration and token usage.

Security:
    - Never logs API keys.
    - Never logs complete prompts.
    - Never logs complete LLM responses.
"""

import json
import logging
from time import perf_counter

import httpx

from app.ai.providers.base_provider import BaseLLMProvider
from app.config.settings import settings


logger = logging.getLogger(__name__)


class DeepSeekProvider(BaseLLMProvider):
    """
    DeepSeek implementation of the AthenaAI LLM provider.

    Uses DeepSeek's chat completions API to analyse trading opportunities.

    Configuration:
        DEEPSEEK_API_KEY: API authentication key.
        DEEPSEEK_MODEL: DeepSeek model identifier.

    API settings:
        TIMEOUT: Maximum API request duration.
        MAX_TOKENS: Maximum generated response tokens.
        TEMPERATURE: Controls response randomness.
    """

    BASE_URL = "https://api.deepseek.com/chat/completions"

    TIMEOUT = 60.0
    MAX_TOKENS = 5000
    TEMPERATURE = 0.2

    async def analyze_trade(self, prompt: str) -> dict:
        """
        Submit a trading analysis prompt to DeepSeek.

        Args:
            prompt: Complete trade analysis prompt generated by TradePrompt.

        Returns:
            dict: Structured JSON analysis returned by DeepSeek.

        Raises:
            ValueError: If API configuration or input is invalid.
            RuntimeError: If API communication or response processing fails.
        """

        # Step 1: Validate API configuration.
        if not settings.DEEPSEEK_API_KEY:
            logger.error(
                "DeepSeek API key is not configured",
                extra={
                    "event": "llm_configuration_failed",
                    "service": "deepseek",
                    "reason": "missing_api_key",
                },
            )

            raise ValueError(
                "DeepSeek API key is missing."
            )

        if not prompt or not prompt.strip():
            logger.warning(
                "DeepSeek analysis received an empty prompt",
                extra={
                    "event": "llm_request_validation_failed",
                    "service": "deepseek",
                    "reason": "empty_prompt",
                },
            )

            raise ValueError(
                "Analysis prompt cannot be empty."
            )

        model = settings.DEEPSEEK_MODEL

        # Step 2: Prepare API request headers.
        headers = {
            "Authorization": f"Bearer {settings.DEEPSEEK_API_KEY}",
            "Content-Type": "application/json",
        }

        # Step 3: Prepare the LLM request payload.
        payload = {
            "model": model,
            "messages": [
                {
                    "role": "system",
                    "content": (
                        "You are AthenaAI. "
                        "Always return ONLY valid JSON."
                    ),
                },
                {
                    "role": "user",
                    "content": prompt,
                },
            ],
            "temperature": self.TEMPERATURE,
            "max_tokens": self.MAX_TOKENS,
            "response_format": {
                "type": "json_object"
            },
        }

        start_time = perf_counter()

        # Step 4: Log the beginning of the LLM request.
        logger.info(
            "DeepSeek analysis request started",
            extra={
                "event": "llm_request_started",
                "service": "deepseek",
                "provider": "deepseek",
                "model": model,
                "max_tokens": self.MAX_TOKENS,
                "temperature": self.TEMPERATURE,
            },
        )

        # Step 5: Send the request to DeepSeek.
        try:
            async with httpx.AsyncClient(
                timeout=self.TIMEOUT
            ) as client:

                response = await client.post(
                    self.BASE_URL,
                    headers=headers,
                    json=payload,
                )

                response.raise_for_status()

        except httpx.HTTPStatusError as exc:
            duration_ms = round(
                (perf_counter() - start_time) * 1000,
                2,
            )

            logger.exception(
                "DeepSeek API returned an HTTP error",
                extra={
                    "event": "llm_http_error",
                    "service": "deepseek",
                    "provider": "deepseek",
                    "model": model,
                    "status_code": exc.response.status_code,
                    "duration_ms": duration_ms,
                },
            )

            raise RuntimeError(
                f"DeepSeek API request failed with status "
                f"{exc.response.status_code}."
            ) from exc

        except httpx.TimeoutException as exc:
            duration_ms = round(
                (perf_counter() - start_time) * 1000,
                2,
            )

            logger.exception(
                "DeepSeek API request timed out",
                extra={
                    "event": "llm_request_timeout",
                    "service": "deepseek",
                    "provider": "deepseek",
                    "model": model,
                    "timeout_seconds": self.TIMEOUT,
                    "duration_ms": duration_ms,
                },
            )

            raise RuntimeError(
                "DeepSeek API request timed out."
            ) from exc

        except httpx.RequestError as exc:
            duration_ms = round(
                (perf_counter() - start_time) * 1000,
                2,
            )

            logger.exception(
                "DeepSeek API communication failed",
                extra={
                    "event": "llm_communication_failed",
                    "service": "deepseek",
                    "provider": "deepseek",
                    "model": model,
                    "duration_ms": duration_ms,
                },
            )

            raise RuntimeError(
                "Unable to communicate with DeepSeek API."
            ) from exc

        # Step 6: Parse and validate the API response.
        try:
            api_result = response.json()

            choices = api_result["choices"]

            if not choices:
                raise ValueError(
                    "DeepSeek returned no analysis choices."
                )

            message = choices[0]["message"]
            content = message["content"]

            if not isinstance(content, str) or not content.strip():
                raise ValueError(
                    "DeepSeek returned empty content."
                )

            analysis_result = json.loads(content)

            if not isinstance(analysis_result, dict):
                raise ValueError(
                    "DeepSeek response must be a JSON object."
                )

        except (
            json.JSONDecodeError,
            KeyError,
            IndexError,
            TypeError,
            ValueError,
        ) as exc:

            duration_ms = round(
                (perf_counter() - start_time) * 1000,
                2,
            )

            logger.exception(
                "Failed to parse or validate DeepSeek response",
                extra={
                    "event": "llm_response_validation_failed",
                    "service": "deepseek",
                    "provider": "deepseek",
                    "model": model,
                    "duration_ms": duration_ms,
                },
            )

            raise RuntimeError(
                "DeepSeek returned an invalid analysis response."
            ) from exc

        # Step 7: Extract available API usage metrics.
        usage = api_result.get("usage") or {}

        prompt_tokens = usage.get("prompt_tokens")
        completion_tokens = usage.get("completion_tokens")
        total_tokens = usage.get("total_tokens")

        finish_reason = choices[0].get("finish_reason")

        duration_ms = round(
            (perf_counter() - start_time) * 1000,
            2,
        )

        # Step 8: Log successful analysis completion.
        logger.info(
            "DeepSeek analysis completed successfully",
            extra={
                "event": "llm_request_completed",
                "service": "deepseek",
                "provider": "deepseek",
                "model": model,
                "status": "success",
                "duration_ms": duration_ms,
                "prompt_tokens": prompt_tokens,
                "completion_tokens": completion_tokens,
                "total_tokens": total_tokens,
                "finish_reason": finish_reason,
                "response_fields": len(analysis_result),
            },
        )

        # Step 9: Return structured analysis to AIOrchestrator.
        return analysis_result
