"""
AI Response

This module defines the final output produced by the AI Intelligence Engine.
The orchestrator combines all agent results into this response.
"""

from dataclasses import dataclass, field
from typing import Any, Dict, List


@dataclass
class AIResponse:
    """
    Final AI response after all agents complete their analysis.
    """

    # Overall AI confidence (0-100)
    confidence: float = 0.0

    # Final AI ranking score
    ranking_score: float = 0.0

    # Priority score for capital allocation
    priority_score: float = 0.0

    # Final recommendation
    decision: str = "HOLD"

    # Human-readable explanations
    explanations: List[str] = field(default_factory=list)

    # Individual agent outputs
    agent_results: Dict[str, Any] = field(default_factory=dict)

    # Additional metadata
    metadata: Dict[str, Any] = field(default_factory=dict)

    def add_explanation(self, message: str) -> None:
        """
        Add an explanation generated by an AI agent.
        """

        self.explanations.append(message)

    def add_agent_result(self, agent: str, result: Any) -> None:
        """
        Store the output from an AI agent.
        """

        self.agent_results[agent] = result

    def update_metadata(self, key: str, value: Any) -> None:
        """
        Store additional metadata.
        """

        self.metadata[key] = value