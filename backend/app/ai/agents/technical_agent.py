"""
Technical Analysis Agent

Analyzes the technical quality of a trade generated by
the Strategy Engine.
"""

from typing import Any, Dict

from app.ai.agents.base_agent import BaseAgent
from app.ai.context import AIContext


class TechnicalAgent(BaseAgent):
    """
    Technical Intelligence Agent.
    """

    async def analyze(
        self,
        context: AIContext
    ) -> Dict[str, Any]:

        candidate = context.trade

        analysis = {
            "trade_score": context.trade_score,
            "volume_ratio": candidate.volume_ratio,
            "distance_from_ma": candidate.distance_from_ma,
            "body_percent": candidate.body_percent,
            "volume_confirmation": candidate.volume_confirmation,
            "quality_pass": candidate.quality_pass,
        }

        confidence = self._calculate_confidence(candidate)

        summary = self._generate_summary(candidate)

        self.add_context_message(
            context,
            summary,
            confidence
        )

        return self.create_result(
            confidence=confidence,
            summary=summary,
            data=analysis
        )

    def _calculate_confidence(
        self,
        candidate
    ) -> float:

        confidence = 50

        if candidate.volume_ratio >= 4:
            confidence += 15
        elif candidate.volume_ratio >= 2:
            confidence += 10
        elif candidate.volume_ratio >= 1.5:
            confidence += 5

        if candidate.distance_from_ma >= 5:
            confidence += 12
        elif candidate.distance_from_ma >= 3:
            confidence += 8

        if candidate.body_percent >= 4:
            confidence += 8
        elif candidate.body_percent >= 3:
            confidence += 5

        if candidate.volume_confirmation:
            confidence += 8

        if candidate.quality_pass:
            confidence += 7

        return min(confidence, 100)

    def _generate_summary(
        self,
        candidate
    ) -> str:

        reasons = []

        if candidate.volume_confirmation:
            reasons.append("Volume confirmed")

        if candidate.body_percent >= 3:
            reasons.append("Strong bullish candle")

        if candidate.distance_from_ma >= 3:
            reasons.append("Healthy trend")

        if candidate.volume_ratio >= 2:
            reasons.append("High buying interest")

        if not reasons:
            return "Average technical setup."

        return ", ".join(reasons)