
from dataclasses import dataclass, field
from typing import Any

from app.models.sector import Sector


@dataclass
class TradeCandidate:
    """
    Stores a stock trading candidate along with its entry parameters,
    technical metrics, ranking scores, risk details, and AI analysis.
    """

    symbol: str                         # Stock trading symbol.
    signal_date: str                    # Date when the trading signal was generated.

    entry_price: float                  # Planned entry price.
    stop_loss: float                    # Initial stop-loss price.
    risk_per_share: float               # Potential risk per share.
    target_2r: float                    # Price target at 2R risk-reward.
    target_3r: float                    # Price target at 3R risk-reward.

    # Technical metrics used for candidate evaluation and future ranking.
    volume_ratio: float                 # Current volume relative to average volume.
    distance_from_ma: float             # Percentage distance from the moving average.
    body_percent: float                 # Percentage size of the candlestick body.
    volume_confirmation: bool           # Indicates whether volume confirms the signal.
    quality_pass: bool                  # Indicates whether the candidate passes quality checks.

    metadata: dict                      # Additional candidate information and technical data.

    total_score: float = 0              # Overall candidate ranking score.
    quantity: int = 0                   # Number of shares allocated for the trade.
    capital_required: float = 0         # Total capital required to execute the trade.

    market_score: float = 0             # Score representing overall market conditions.
    sector_score: float = 0              # Score representing the candidate's sector performance.
    sector: Sector = Sector.UNKNOWN     # Sector classification of the stock.

    risk_amount: float = 0              # Total monetary risk associated with the trade.

    ai_confidence: float = 0.0          # Confidence score generated by the AI engine.
    ai_decision: str = "WATCH"           # AI recommendation (BUY, HOLD, REJECT, or WATCH).
    ai_explanations: list[str] = field(default_factory=list)  # Explanations supporting the AI decision.
    ai_results: dict[str, Any] = field(default_factory=dict)  # Detailed AI analysis results.
