@router.get(
    "/signals/{symbol}",
    summary="Load Backtesting Signals",
    description="Loads the generated trading signals for the specified symbol.",
)
def load_signals(
    symbol: str,
    db: Session = Depends(get_db),
):
    """
    Load trading signals for a symbol and return the total signal count.
    """

    signals = run_backtest_operation(
        operation="load_signals",
        event="backtest_signals_loaded",
        func=lambda: service.load_signals(db, symbol),
        symbol=symbol,
    )

    logger.info(
        "Backtesting signal count calculated",
        extra={
            "event": "backtest_signal_count_calculated",
            "service": "backtesting",
            "symbol": symbol,
            "total_signals": len(signals),
        },
    )

    return {
        "symbol": symbol,
        "total_signals": len(signals),
    }


