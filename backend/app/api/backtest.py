# ---------------------------------------------------------------------
# Shared backtesting execution and logging helper
# ---------------------------------------------------------------------

def run_backtest_operation(
    operation: str,
    event: str,
    func: Callable[[], Any],
    **context: Any,
) -> Any:
    """
    Execute a backtesting operation with structured business logging.

    Logs:
        - Operation started
        - Operation completed
        - Execution duration
        - Exceptions with stack traces

    The JSON logging formatter automatically attaches the request ID.
    """

    start_time = perf_counter()

    logger.info(
        "Backtesting operation started",
        extra={
            "event": f"{event}_started",
            "service": "backtesting",
            "operation": operation,
            **context,
        },
    )

    try:
        result = func()

        duration_ms = round(
            (perf_counter() - start_time) * 1000,
            2,
        )

        logger.info(
            "Backtesting operation completed",
            extra={
                "event": event,
                "service": "backtesting",
                "operation": operation,
                "duration_ms": duration_ms,
                **context,
            },
        )

        return result

    except Exception:
        duration_ms = round(
            (perf_counter() - start_time) * 1000,
            2,
        )

        logger.exception(
            "Backtesting operation failed",
            extra={
                "event": f"{event}_failed",
                "service": "backtesting",
                "operation": operation,
                "duration_ms": duration_ms,
                **context,
            },
        )

        raise


